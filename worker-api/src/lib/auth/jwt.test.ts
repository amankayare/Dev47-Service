import { describe, expect, it } from "vitest";
import {
  authenticateRequest,
  createJwtToken,
  decodeJwtToken,
  extractTokenFromHeader,
  isJwtError,
  requireAdmin,
} from "./jwt";

describe("JWT Utilities", () => {
  const secret = "test-secret-key-12345";

  it("creates and decodes a valid HS256 JWT token", () => {
    const token = createJwtToken("testuser", 42, true, secret);
    expect(typeof token).toBe("string");
    expect(token.split(".").length).toBe(3);

    const decoded = decodeJwtToken(token, secret);
    expect(isJwtError(decoded)).toBe(false);
    if (!isJwtError(decoded)) {
      expect(decoded.sub).toBe("testuser");
      expect(decoded.user_id).toBe(42);
      expect(decoded.is_admin).toBe(true);
      expect(decoded.exp).toBeGreaterThan(Math.floor(Date.now() / 1000));
    }
  });

  it("verifies a token generated by Python PyJWT", () => {
    // Generated with PyJWT: sub='pyuser', user_id=99, is_admin=True, secret='compat-secret'
    const pyToken =
      "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiJweXVzZXIiLCJ1c2VyX2lkIjo5OSwiaXNfYWRtaW4iOnRydWUsImV4cCI6MjEwOTQ5NjUyMn0.JProzLKcqbK4X3K7LH_92--3MTZzpADeu5Car30YW7I";
    const decoded = decodeJwtToken(pyToken, "compat-secret");
    expect(isJwtError(decoded)).toBe(false);
    if (!isJwtError(decoded)) {
      expect(decoded.sub).toBe("pyuser");
      expect(decoded.user_id).toBe(99);
      expect(decoded.is_admin).toBe(true);
    }
  });

  it("rejects tokens signed with a different secret", () => {
    const token = createJwtToken("testuser", 42, false, secret);
    const decoded = decodeJwtToken(token, "wrong-secret");
    expect(isJwtError(decoded)).toBe(true);
    if (isJwtError(decoded)) {
      expect(decoded.error).toBe("invalid_token");
      expect(decoded.message).toBe("Invalid token");
    }
  });

  it("detects expired tokens", () => {
    // Manually construct an expired token
    const header = Buffer.from(JSON.stringify({ alg: "HS256", typ: "JWT" })).toString("base64url");
    const payload = Buffer.from(
      JSON.stringify({
        sub: "expiredUser",
        user_id: 1,
        is_admin: false,
        exp: Math.floor(Date.now() / 1000) - 100, // 100s in past
      }),
    ).toString("base64url");
    const crypto = require("node:crypto");
    const signature = crypto
      .createHmac("sha256", secret)
      .update(`${header}.${payload}`)
      .digest()
      .toString("base64url");
    const expiredToken = `${header}.${payload}.${signature}`;

    const decoded = decodeJwtToken(expiredToken, secret);
    expect(isJwtError(decoded)).toBe(true);
    if (isJwtError(decoded)) {
      expect(decoded.error).toBe("token_expired");
      expect(decoded.message).toBe("Token has expired");
    }
  });

  it("extracts token with or without 'Bearer ' prefix", () => {
    expect(extractTokenFromHeader("Bearer myToken123")).toBe("myToken123");
    expect(extractTokenFromHeader("myToken123")).toBe("myToken123");
    expect(extractTokenFromHeader(null)).toBe(null);
    expect(extractTokenFromHeader("")).toBe(null);
  });

  it("authenticates valid request and rejects missing token", async () => {
    const token = createJwtToken("admin", 1, true, secret);

    const validReq = new Request("http://localhost/api/test", {
      headers: { Authorization: `Bearer ${token}` },
    });
    const result = authenticateRequest(validReq, secret);
    expect(result.authenticated).toBe(true);
    if (result.authenticated) {
      expect(result.user.sub).toBe("admin");
      expect(result.user.is_admin).toBe(true);
    }

    const missingReq = new Request("http://localhost/api/test");
    const missingResult = authenticateRequest(missingReq, secret);
    expect(missingResult.authenticated).toBe(false);
    if (!missingResult.authenticated) {
      expect(missingResult.response.status).toBe(401);
      const json = await missingResult.response.json();
      expect(json).toEqual({
        error: "no_token",
        message: "Authorization token required",
      });
    }
  });

  it("enforces admin required", async () => {
    const regularToken = createJwtToken("user", 2, false, secret);
    const nonAdminReq = new Request("http://localhost/api/admin", {
      headers: { Authorization: `Bearer ${regularToken}` },
    });
    const adminCheck = requireAdmin(nonAdminReq, secret);
    expect(adminCheck.authenticated).toBe(false);
    if (!adminCheck.authenticated) {
      expect(adminCheck.response.status).toBe(403);
      const json = await adminCheck.response.json();
      expect(json).toEqual({
        error: "admin_required",
        message: "Admin privileges required",
      });
    }

    const adminToken = createJwtToken("admin", 1, true, secret);
    const adminReq = new Request("http://localhost/api/admin", {
      headers: { Authorization: `Bearer ${adminToken}` },
    });
    const adminPass = requireAdmin(adminReq, secret);
    expect(adminPass.authenticated).toBe(true);
  });
});
